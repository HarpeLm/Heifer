//! AV1 decoder for AVIF images.
//!
//! Spec: AV1 Bitstream & Decoding Process Specification (AOMedia). The bitstream structure is
//! read by [`obu`] (OBUs), [`sequence`] (the sequence header), [`frame`] (frame headers),
//! [`tile`] (tiles) and [`symbol`] (the symbol decoder); [`decode`] reconstructs frames, intra
//! ones on their own with [`decode_frame`] and every frame of a stream, inter frames included,
//! with a [`Decoder`]. Film grain is not applied.

pub mod decode;
pub mod frame;
pub mod obu;
pub mod sequence;
pub mod symbol;
pub mod tile;

mod bits;
#[rustfmt::skip] // generated by scripts/gen-av1-tables.py
mod cdf_tables;
mod predict;
#[rustfmt::skip] // generated by scripts/gen-av1-tables.py
mod spec_tables;
mod transform;

pub use decode::{Decoder, Picture, decode_frame};
pub use frame::{FrameHeader, FrameType};
pub use obu::{Obu, ObuType, obus};
pub use sequence::SequenceHeader;
pub use symbol::SymbolDecoder;
pub use tile::{CodedFrame, Tile, frames};

/// Errors returned while reading an AV1 bitstream.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
#[non_exhaustive]
pub enum Error {
    /// The bitstream ended before a complete syntax element could be read.
    #[error("unexpected end of bitstream")]
    UnexpectedEof,
    /// A syntax element has a value forbidden by the specification.
    #[error("invalid bitstream: {0}")]
    Invalid(&'static str),
    /// A valid feature this decoder does not handle.
    #[error("unsupported AV1 feature: {0}")]
    Unsupported(&'static str),
}
